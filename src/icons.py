def get_pixmap(name: str, color: str = "#a6abb8", size: int = 16) -> QPixmap:
    """Render an SVG template to a crisp QPixmap."""
    svg_code = SVG_TEMPLATES.get(name)
    if not svg_code:
        # Fallback to empty transparent pixmap
        pm = QPixmap(size, size)
        pm.fill(QColor(0, 0, 0, 0))
        return pm

    filled_svg = svg_code.replace("{color}", color)
    byte_arr = QByteArray(filled_svg.encode("utf-8"))
    renderer = QSvgRenderer(byte_arr)

    pixmap = QPixmap(size, size)
    pixmap.fill(QColor(0, 0, 0, 0))

    painter = QPainter(pixmap)
    renderer.render(painter)
    painter.end()

    return pixmap


def get_icon(name: str, color: str = "#a6abb8", size: int = 16) -> QIcon:
    """Return a QIcon for buttons and labels."""
    pixmap = get_pixmap(name, color=color, size=size)
    return QIcon(pixmap)
